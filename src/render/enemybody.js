import { rr } from "./icons.js";

/* drawEnemyBody draws one enemy at origin; the render bob stays in the
   drawEnemies wrapper (positioning concern) so bodies stay translate-free. */
export function drawEnemyBody(c, world, e) {
  const r = e.r;
  const t = e.type;
  if (t === "stationary") {
    const s = 1 + Math.sin(world.time * 3) * 0.06;
    c.scale(s, s);
    c.fillStyle = "#1a0c18";
    rr(c, -r * 0.82, -r * 0.82, r * 1.64, r * 1.64, 4);
    c.fill();
    c.fillStyle = "#2a1030";
    rr(c, -r * 0.72, -r * 0.72, r * 1.44, r * 1.44, 5);
    c.fill();
    c.fillStyle = e.color;
    rr(c, -r * 0.48, -r * 0.48, r * 0.96, r * 0.96, 3);
    c.fill();
    c.fillStyle = "#150a1c";
    c.fillRect(-r * 0.4, -r * 0.12, r * 0.8, r * 0.2);
    c.fillStyle = e.color;
    c.globalAlpha = 0.45;
    c.fillRect(-r * 0.32, -r * 0.04, r * 0.64, r * 0.06);
    c.globalAlpha = 1;
    c.fillStyle = "#1a0c18";
    c.fillRect(-r * 0.1, -r * 1.05, r * 0.2, r * 0.28);
    c.fillStyle = "#3a1844";
    c.fillRect(-r * 0.06, -r * 1.22, r * 0.12, r * 0.2);
  } else if (t === "rocket") {
    c.fillStyle = "#3a1c10";
    rr(c, -r * 0.62, r * 0.08, r * 1.24, r * 0.72, 3);
    c.fill();
    c.fillStyle = e.color;
    c.beginPath();
    c.moveTo(0, -r);
    c.lineTo(r * 0.72, r * 0.28);
    c.lineTo(-r * 0.72, r * 0.28);
    c.closePath();
    c.fill();
    c.fillStyle = "#2a140c";
    c.beginPath();
    c.moveTo(-r * 0.72, r * 0.12);
    c.lineTo(-r * 1.05, r * 0.42);
    c.lineTo(-r * 0.55, r * 0.42);
    c.closePath();
    c.fill();
    c.beginPath();
    c.moveTo(r * 0.72, r * 0.12);
    c.lineTo(r * 1.05, r * 0.42);
    c.lineTo(r * 0.55, r * 0.42);
    c.closePath();
    c.fill();
    c.fillStyle = "#1a1008";
    c.fillRect(-r * 0.22, -r * 0.08, r * 0.44, r * 0.16);
    c.fillStyle = Math.floor(world.time * 10) % 2 ? "#ffde7a" : "#ff7a3a";
    c.beginPath();
    c.arc(0, r * 0.62, r * 0.2 + Math.sin(world.time * 20) * 0.03, 0, 7);
    c.fill();
  } else if (t === "boomerang") {
    c.save();
    c.rotate(world.time * 10);
    c.strokeStyle = "#3a1028";
    c.lineWidth = r * 0.46;
    c.lineCap = "round";
    c.beginPath();
    c.arc(0, 0, r * 0.7, 0, Math.PI * 1.5);
    c.stroke();
    c.strokeStyle = e.color;
    c.lineWidth = r * 0.3;
    c.beginPath();
    c.arc(0, 0, r * 0.7, 0, Math.PI * 1.5);
    c.stroke();
    c.restore();
    c.fillStyle = "#120814";
    c.beginPath();
    c.arc(0, 0, r * 0.22, 0, 7);
    c.fill();
    c.strokeStyle = e.color;
    c.lineWidth = 1.4;
    c.beginPath();
    c.arc(0, 0, r * 0.22, 0, 7);
    c.stroke();
  } else if (t === "burrow") {
    c.fillStyle = "#3a2414";
    c.beginPath();
    c.ellipse(0, r * 0.12, r * 0.95, r * 0.62, 0, 0, 7);
    c.fill();
    c.fillStyle = e.color;
    c.beginPath();
    c.ellipse(0, 0, r * 0.88, r * 0.55, 0, 0, 7);
    c.fill();
    c.fillStyle = "#2a180c";
    c.fillRect(-r * 0.7, -r * 0.08, r * 1.4, r * 0.1);
    c.fillRect(-r * 0.55, r * 0.16, r * 1.1, r * 0.08);
    c.fillStyle = "#1a1008";
    c.beginPath();
    c.moveTo(-r * 0.55, -r * 0.2);
    c.lineTo(-r * 0.95, r * 0.08);
    c.lineTo(-r * 0.42, r * 0.02);
    c.closePath();
    c.fill();
    c.beginPath();
    c.moveTo(r * 0.55, -r * 0.2);
    c.lineTo(r * 0.95, r * 0.08);
    c.lineTo(r * 0.42, r * 0.02);
    c.closePath();
    c.fill();
    c.fillStyle = "#0a0804";
    c.fillRect(-r * 0.28, -r * 0.22, r * 0.18, r * 0.12);
    c.fillRect(r * 0.1, -r * 0.22, r * 0.18, r * 0.12);
  } else if (t === "shade") {
    c.fillStyle = "#0c1024";
    c.beginPath();
    c.moveTo(0, -r);
    c.lineTo(r * 0.72, 0);
    c.lineTo(0, r * 0.95);
    c.lineTo(-r * 0.72, 0);
    c.closePath();
    c.fill();
    c.fillStyle = e.color;
    c.beginPath();
    c.moveTo(0, -r * 0.72);
    c.lineTo(r * 0.48, 0);
    c.lineTo(0, r * 0.68);
    c.lineTo(-r * 0.48, 0);
    c.closePath();
    c.fill();
    c.fillStyle = "#060814";
    c.beginPath();
    c.arc(0, -r * 0.04, r * 0.2, 0, 7);
    c.fill();
    c.globalAlpha = 0.45;
    c.fillStyle = e.color;
    c.fillRect(-r * 0.9, r * 0.35, r * 0.28, r * 0.08);
    c.fillRect(r * 0.62, r * 0.42, r * 0.28, r * 0.08);
    c.globalAlpha = 1;
  } else if (t === "knight") {
    c.fillStyle = "#2a2210";
    c.beginPath();
    c.moveTo(0, -r * 1.05);
    c.lineTo(r * 0.78, -r * 0.35);
    c.lineTo(r * 0.62, r * 0.72);
    c.lineTo(-r * 0.62, r * 0.72);
    c.lineTo(-r * 0.78, -r * 0.35);
    c.closePath();
    c.fill();
    c.fillStyle = e.color;
    c.beginPath();
    c.moveTo(0, -r * 0.88);
    c.lineTo(r * 0.58, -r * 0.28);
    c.lineTo(r * 0.46, r * 0.52);
    c.lineTo(-r * 0.46, r * 0.52);
    c.lineTo(-r * 0.58, -r * 0.28);
    c.closePath();
    c.fill();
    c.fillStyle = "#1a1408";
    c.fillRect(-r * 0.08, -r * 0.55, r * 0.16, r * 0.7);
    c.fillRect(-r * 0.38, -r * 0.08, r * 0.76, r * 0.14);
    c.fillStyle = "#8a6a28";
    c.fillRect(-r * 0.06, -r * 1.22, r * 0.12, r * 0.28);
    c.fillStyle = e.color;
    c.beginPath();
    c.moveTo(0, -r * 1.38);
    c.lineTo(r * 0.16, -r * 1.12);
    c.lineTo(-r * 0.16, -r * 1.12);
    c.closePath();
    c.fill();
    c.fillStyle = "#1a1408";
    c.fillRect(-r * 0.7, r * 0.42, r * 0.28, r * 0.22);
    c.fillRect(r * 0.42, r * 0.42, r * 0.28, r * 0.22);
  } else {
    if (t === "chaser") c.scale(0.72, 1.42);
    else if (t === "fast") c.scale(1.42, 0.7);
    c.fillStyle = "#0a1018";
    c.beginPath();
    c.arc(0, r * 0.06, r * 0.98, 0, 7);
    c.fill();
    c.fillStyle = e.color;
    c.beginPath();
    c.arc(0, 0, r * 0.88, 0, 7);
    c.fill();
    c.strokeStyle = "#0a0d14";
    c.lineWidth = 1.75;
    c.beginPath();
    c.arc(0, 0, r * 0.88, 0, 7);
    c.stroke();
    if (t === "chaser") {
      c.fillStyle = e.color;
      c.beginPath();
      c.moveTo(-r * 0.22, -r * 0.68);
      c.lineTo(0, -r * 1.22);
      c.lineTo(r * 0.22, -r * 0.68);
      c.closePath();
      c.fill();
      c.strokeStyle = "#0a0d14";
      c.lineWidth = 2;
      c.stroke();
      c.fillStyle = "#0a1018";
      c.fillRect(-r * 0.42, -r * 0.22, r * 0.84, r * 0.2);
      c.fillStyle = e.color;
      c.globalAlpha = 0.4;
      c.fillRect(-r * 0.34, -r * 0.16, r * 0.68, r * 0.08);
      c.globalAlpha = 1;
      c.fillStyle = "#0a1018";
      c.fillRect(-r * 0.38, r * 0.28, r * 0.76, r * 0.16);
    } else if (t === "fast") {
      c.fillStyle = "#1a1408";
      c.fillRect(-r * 0.7, -r * 0.22, r * 0.28, r * 0.16);
      c.fillRect(r * 0.42, -r * 0.22, r * 0.28, r * 0.16);
      c.fillStyle = "rgba(255,210,71,0.5)";
      for (let i = 1; i <= 3; i++)
        c.fillRect(-r * 1.1 - i * 3, -r * 0.1 + i * 0.05, r * 0.5, r * 0.12);
    } else {
      c.fillStyle = "#071018";
      c.fillRect(-r * 0.55, -r * 0.18, r * 1.1, r * 0.22);
      c.fillStyle = e.color;
      c.globalAlpha = 0.45;
      c.fillRect(-r * 0.46, -r * 0.1, r * 0.92, r * 0.08);
      c.globalAlpha = 1;
      c.fillStyle = "#1a2a22";
      c.fillRect(-r * 0.72, r * 0.08, r * 0.28, r * 0.22);
      c.fillRect(r * 0.44, r * 0.08, r * 0.28, r * 0.22);
      c.fillStyle = "#071018";
      c.fillRect(-r * 0.38, -r * 0.02, r * 0.76, r * 0.36);
    }
    c.fillStyle = "#0a0f1a";
    c.fillRect(-r * 0.48, r * 0.62, r * 0.32, r * 0.22);
    c.fillRect(r * 0.16, r * 0.62, r * 0.32, r * 0.22);
  }
  if (e.invuln && Math.floor(world.time * 12) % 2) c.globalAlpha = 0.5;
}
